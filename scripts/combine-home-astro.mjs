import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const legacy=path.join(root,'dist');
const astro=path.join(root,'apps/home-astro/dist');
const output=path.join(root,'.home-astro-preview');
const list=(dir,prefix='')=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?list(path.join(dir,e.name),prefix+e.name+'/'):[prefix+e.name]);
const hash=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
for(const dir of [legacy,astro])if(!fs.existsSync(path.join(dir,'index.html')))throw Error(`Build missing: ${dir}`);
const newFiles=list(astro);
for(const file of newFiles)if(!['index.html','es/index.html'].includes(file)&&!file.startsWith('home-astro/'))throw Error(`Unscoped Astro file: ${file}`);
if(output!==path.resolve(root,'.home-astro-preview'))throw Error('Unsafe output path');
fs.rmSync(output,{recursive:true,force:true});
fs.cpSync(legacy,output,{recursive:true});
fs.cpSync(astro,output,{recursive:true});
const baseline=list(legacy).filter(f=>!['index.html','es/index.html'].includes(f));
const changed=baseline.filter(f=>hash(path.join(legacy,f))!==hash(path.join(output,f)));
if(changed.length)throw Error(`Interior files changed: ${changed.join(', ')}`);
fs.writeFileSync(path.join(root,'docs/home-astro/merge-verification.json'),JSON.stringify({checked:new Date().toISOString(),unchangedLegacyFiles:baseline.length,replaced:['index.html','es/index.html'],newFiles:newFiles.filter(f=>f.startsWith('home-astro/')),changed},null,2));
console.log(`Combined preview ready. ${baseline.length} legacy files byte-identical.`);
